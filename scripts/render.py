#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""从 data/versions.yaml 生成 README.md（中文）与 README.en.md（英文）。

用法:
    python scripts/render.py

设计约定:
  * 判断"滞后"以 meta.last_checked 为基准，而不是当天日期。
    这样同样的数据无论哪天运行都产出同样的结果，避免无意义的 diff。
    想刷新状态，就改 last_checked 并重跑。
  * 只改 data/versions.yaml，不要手工改 README。
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit(
        "缺少依赖 pyyaml。请先运行：\n"
        "    python -m pip install -r scripts/requirements.txt"
    )

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "versions.yaml"
REPO = "liufuyou/EhViewer"

STATUS_LABEL = {
    "active": ("活跃", "Active"),
    "stale": ("滞后", "Stale"),
    "taken_down": ("已下架", "Taken down"),
    "archived": ("已归档", "Archived"),
}

BANNER_ZH = "<!-- 本文件由 scripts/render.py 生成，请勿直接编辑。修改 data/versions.yaml 后重新运行脚本。 -->"
BANNER_EN = "<!-- Generated by scripts/render.py. Do not edit directly. Edit data/versions.yaml and re-run. -->"


def parse_date(value) -> date | None:
    if not value:
        return None
    if isinstance(value, date):
        return value
    return date.fromisoformat(str(value))


def effective_status(variant: dict, anchor: date, stale_days: int) -> str:
    """显式状态优先；否则按发布日期判断是否滞后。"""
    explicit = variant.get("status")
    if explicit in ("taken_down", "archived"):
        return explicit
    released = parse_date(variant.get("released"))
    if released and (anchor - released).days > stale_days:
        return "stale"
    if explicit == "stale":
        return "stale"
    return "active"


def cell(text: str | None) -> str:
    if text is None or text == "":
        return "—"
    return str(text).replace("|", "\\|")


def version_cell(variant: dict, lang: str) -> str:
    """版本号单元格。若存在 prerelease，附一行小字说明，不计入"最新版本"。"""
    base = cell(variant.get("version"))
    pre = variant.get("prerelease") or {}
    pre_version = pre.get("version")
    if pre_version:
        tag = "预发布" if lang == "zh" else "pre-release"
        base = f"{base}<br><sub>{tag} {pre_version}</sub>"
    return base


def render_table(variants: list[dict], lang: str, anchor: date, stale_days: int) -> list[str]:
    if lang == "zh":
        head = "| 版本 | 平台 | 状态 | 最新版本 | 发布日期 | 获取 |"
    else:
        head = "| Variant | Platform | Status | Latest | Released | Get |"
    lines = [head, "| --- | --- | --- | --- | --- | --- |"]

    for v in variants:
        status = effective_status(v, anchor, stale_days)
        label = STATUS_LABEL[status][0 if lang == "zh" else 1]
        # name_en 可选，用于名称本身含中文、但英文版需要另一种写法的条目
        name = (v.get("name_en") or v["name"]) if lang == "en" else v["name"]

        # 带上别名，方便对号入座
        nickname = v.get("nickname_zh") if lang == "zh" else v.get("nickname_en")
        if nickname:
            name = f"{name}（{nickname}）" if lang == "zh" else f"{name} ({nickname})"

        note = v.get("zh_note") if lang == "zh" else v.get("en_note")
        platform = v.get("platform", "")
        # "全平台 / All platforms" 这类双语值，按语言取对应的一侧
        if " / " in platform:
            zh_part, en_part = platform.split(" / ", 1)
            platform = zh_part if lang == "zh" else en_part

        if status == "taken_down":
            name = f"~~{name}~~"
            version = version_cell(v, lang)
            released = cell(v.get("released"))
            link = "—"
        else:
            version = version_cell(v, lang)
            released = cell(v.get("released"))
            url = v.get("url")
            if url:
                is_release = "/releases" in url
                if lang == "zh":
                    link = f"[{'下载' if is_release else '项目'}]({url})"
                else:
                    link = f"[{'Download' if is_release else 'Project'}]({url})"
            else:
                link = "—"

        # 备注并入名称单元格，避免出现整行空单元格
        name_cell = f"{name}<br><sub>{note}</sub>" if note else name

        row = f"| {name_cell} | {cell(platform)} | {label} | {version} | {released} | {link} |"
        lines.append(row)

    return lines


def build(lang: str, data: dict) -> str:
    meta = data["meta"]
    anchor = parse_date(meta["last_checked"])
    stale_days = int(meta.get("stale_after_days", 180))
    groups = {g["id"]: g for g in data["groups"]}
    variants = data["variants"]

    by_group: dict[str, list[dict]] = {gid: [] for gid in groups}
    for v in variants:
        by_group[v["group"]].append(v)

    available = sum(
        1 for v in variants if effective_status(v, anchor, stale_days) in ("active", "stale")
    )
    gone = len(variants) - available
    checked = anchor.isoformat()

    out: list[str] = []
    out.append(BANNER_ZH if lang == "zh" else BANNER_EN)
    out.append("")

    # 标题与语言切换
    out.append("<h1 align=\"center\">EhViewer</h1>")
    out.append("")
    if lang == "zh":
        out.append('<p align="center"><b>简体中文</b> · <a href="./README.en.md">English</a></p>')
    else:
        out.append('<p align="center"><a href="./README.md">简体中文</a> · <b>English</b></p>')
    out.append("")

    # 徽章：只用 shields.io，全部是静态值，不会因为第三方服务倒闭而裂图
    out.append(
        f'<p align="center">'
        f'<img alt="stars" src="https://img.shields.io/github/stars/{REPO}?style=flat&logo=github"> '
        f'<img alt="last checked" src="https://img.shields.io/badge/last%20checked-{checked}-blue"> '
        f'<img alt="available" src="https://img.shields.io/badge/available-{available}-brightgreen">'
        f"</p>"
    )
    out.append("")

    if lang == "zh":
        out.append("<p align=\"center\">EhViewer 是一个 E-Hentai 阅读器合集，提供目前仍然可用的版本。</p>")
        out.append("")
        out.append(
            f"> **维护状态**：最后核对 `{checked}` · 可用版本 {available} 个 · "
            f"已下架/归档 {gone} 个 · 本页由清单自动生成"
        )
    else:
        out.append("<p align=\"center\">A curated index of E-Hentai viewers that are still available.</p>")
        out.append("")
        out.append(
            f"> **Status**: last checked `{checked}` · {available} available · "
            f"{gone} taken down / archived · generated from a single manifest"
        )
    out.append("")

    if lang == "zh":
        out.append("## 先用最新版")
        out.append("")
        out.append(
            "遇到无法翻页、缩略图加载失败等问题，**先确认自己用的是下表里最新的版本**。"
            "绝大多数这类问题在最新版里已经修好，不需要额外设置。"
        )
    else:
        out.append("## Update first")
        out.append("")
        out.append(
            "If pagination or thumbnails break, **confirm you are on the latest build listed below**. "
            "Most of these issues are already fixed upstream and need no extra configuration."
        )
    out.append("")

    # 各分组表格
    for gid, group in groups.items():
        items = by_group.get(gid, [])
        if not items:
            continue
        title = group["zh"] if lang == "zh" else group["en"]
        intro = group.get("zh_intro") if lang == "zh" else group.get("en_intro")
        out.append(f"## {title}")
        out.append("")
        if intro:
            out.append(f"> {intro}")
            out.append("")
        out.extend(render_table(items, lang, anchor, stale_days))
        out.append("")

    # 选择建议
    if lang == "zh":
        out.append("## 该选哪个")
        out.append("")
        out.append("按平台选就行，同平台内没有绝对的对错：")
        out.append("")
        out.append("- **Android**：先用 NekoInverter（改动保守）或 SXJ（中文优化）；偏好新界面再试 MD3 衍生版")
        out.append("- **iOS**：EhPanda")
        out.append("- **桌面 / 跨平台**：JHenTai")
        out.append("")
        out.append("换版本前请先备份收藏和阅读记录，不同分支的数据格式不一定兼容。")
        out.append("")
        out.append("## 提问前")
        out.append("")
        out.append(
            "请先读[《提问的智慧》](http://www.catb.org/~esr/faqs/smart-questions.html)，"
            "并在提问时说明：设备型号、系统版本、你用的具体版本号、复现步骤。"
        )
        out.append("")
        out.append(
            "所有 App 都是第三方作品。请尽量不要在评论区点名其他 App，"
            "需要的话把本项目链接发给对方即可。"
        )
        out.append("")
        out.append("> 无论何时何地，都没有人有权力要求其他人不断为爱发电。")
    else:
        out.append("## Which one")
        out.append("")
        out.append("Pick by platform; within a platform there is no single right answer:")
        out.append("")
        out.append("- **Android**: start with NekoInverter (conservative) or SXJ (Chinese-oriented); try MD3 forks if you want the newer UI")
        out.append("- **iOS**: EhPanda")
        out.append("- **Desktop / cross-platform**: JHenTai")
